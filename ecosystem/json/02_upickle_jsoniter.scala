//> using scala 3.9.0
//> using dep com.lihaoyi::upickle:4.4.3
//> using dep com.github.plokhotnyuk.jsoniter-scala::jsoniter-scala-core:2.42.2
//> using dep com.github.plokhotnyuk.jsoniter-scala::jsoniter-scala-macros:2.42.2
// Run: scala-cli run ecosystem/json/02_upickle_jsoniter.scala
//
// Two alternatives to circe:
//   * upickle (Li Haoyi): simple API (write/read), ReadWriter type class, also MessagePack;
//     ujson.Value is a MUTABLE, convenient JSON AST.
//   * jsoniter-scala: compile-time generated codecs, the fastest JSON library on the JVM;
//     no AST — it reads/writes your types directly.

package ecosystem.json.alternatives

import upickle.default.{ReadWriter, read, write, writeJs}
import com.github.plokhotnyuk.jsoniter_scala.core.*
import com.github.plokhotnyuk.jsoniter_scala.macros.*

case class Pet(name: String, species: String, age: Int = 1) derives ReadWriter
case class Owner(name: String, pets: List[Pet], nickname: Option[String] = None) derives ReadWriter

enum Status derives ReadWriter:
  case Active, Suspended

// jsoniter-scala codecs are generated by a macro
case class Event(id: Long, kind: String, payload: Map[String, Double])
given JsonValueCodec[Event] = JsonCodecMaker.make
given JsonValueCodec[List[Event]] = JsonCodecMaker.make

@main def run(): Unit =
  section("upickle: write & read")
  val owner = Owner("Ada", List(Pet("Rex", "dog", 3), Pet("Tom", "cat")))
  val json = write(owner)
  println(json)                                  // defaults (age = 1, nickname = None) are omitted
  println(write(owner, indent = 2).linesIterator.take(4).mkString("\n") + "\n  ...")
  println(read[Owner](json) == owner)
  println(read[Owner]("""{"name":"Bob","pets":[{"name":"Fido","species":"dog"}]}"""))  // defaults filled in
  println(write(Status.Suspended))
  // upickle 4 wraps failures in a TraceException whose message is the JSON path ($ = root):
  try read[Owner]("""{"pets":[]}""")
  catch case e: upickle.core.TraceVisitor.TraceException =>
    println(s"  error at ${e.getMessage}: ${e.getCause.getMessage}")
  try read[Owner]("""{"name":"X","pets":[{"name":"Rex","species":"dog","age":"old"}]}""")
  catch case e: upickle.core.TraceVisitor.TraceException =>
    println(s"  error at ${e.getMessage}: ${e.getCause.getMessage}")

  section("ujson: a mutable JSON AST")
  val doc = ujson.read("""{"user":{"name":"Ada","langs":["scala"]}}""")
  println(doc("user")("name").str)
  doc("user")("langs").arr += "haskell"          // mutate in place
  doc("user")("active") = true
  println(ujson.write(doc))
  val built = ujson.Obj("x" -> 1, "y" -> ujson.Arr(1, 2, 3), "z" -> ujson.Null)
  println(built.render())
  println(writeJs(Pet("Kit", "cat")))            // case class → ujson.Value

  section("MessagePack (binary) with the same ReadWriter")
  val bytes = upickle.default.writeBinary(owner)
  println(s"  ${bytes.length} bytes vs ${json.getBytes.length} bytes of JSON")
  println(upickle.default.readBinary[Owner](bytes) == owner)

  section("jsoniter-scala: macro-generated codecs")
  val events = List(Event(1, "click", Map("x" -> 10.5, "y" -> 3)), Event(2, "scroll", Map.empty))
  val out = writeToString(events)
  println(out)
  println(readFromString[List[Event]](out) == events)
  try readFromString[Event]("""{"id":"oops"}""")
  catch case e: JsonReaderException => println(s"  error: ${e.getMessage.linesIterator.next()}")

  section("Which one?")
  // circe     — FP-friendly, rich AST and cursors, Typelevel integration (http4s, fs2)
  // upickle   — simplest API, Li Haoyi ecosystem (requests, cask), MessagePack
  // jsoniter  — raw speed and low allocation; codecs are configured via JsonCodecMaker
  // zio-json  — the ZIO ecosystem's choice
  println("see comments")

def section(title: String): Unit = println(s"\n=== $title ===")
